/* Builds ONE self-contained HTML file: CSS + JS + product photo inlined, so the
   page opens from file:// or any static host with zero external requests.
   Run after `npm run build`:  node scripts/inline.mjs  */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, copyFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const DIST = join(ROOT, 'dist')
const OUT_DIR = join(ROOT, 'standalone')
const OUT_NAME = 'PhosphoPower-landing.html'

let html = readFileSync(join(DIST, 'index.html'), 'utf8')

/* ── 1. CSS ─────────────────────────────────────────────────────────────── */
const cssFile = readdirSync(join(DIST, 'assets')).find((f) => f.endsWith('.css'))
let css = readFileSync(join(DIST, 'assets', cssFile), 'utf8')
css = css.replace(/<\/style/gi, '<\\/style')
html = html.replace(/<link[^>]+href="[^"]*\.css"[^>]*>/i, () => `<style>\n${css}\n</style>`)

/* ── 2. JS: load bundle, swap the photo to a data URI, THEN inline ───────── */
const imgPath = join(DIST, 'product.png')
const b64 = readFileSync(imgPath).toString('base64')
const dataUri = `data:image/jpeg;base64,${b64}`

const jsFile = readdirSync(join(DIST, 'assets')).find((f) => f.endsWith('.js'))
let js = readFileSync(join(DIST, 'assets', jsFile), 'utf8')
const before = js
js = js.replace('src:`/product.png`', 'src:`' + dataUri + '`')
if (js === before) throw new Error('img src site not found in bundle — did the build output change?')
js = js.replace(/<\/script/gi, '<\\/script')
// JSON-LD's inert `image:"/product.png"` is left alone on purpose: it is metadata,
// not a request, and inlining 260 KB there would bloat the schema block.

html = html.replace(/<script[^>]+src="[^"]*\.js"[^>]*><\/script>/i, () => `<script type="module">\n${js}\n</script>`)

/* ── 4. no absolute asset references may survive ────────────────────────── */
const leftovers = [...html.matchAll(/(?:src|href)="(\/[^"]+)"/g)].map((m) => m[1]).filter((u) => !u.startsWith('#'))
if (leftovers.length) {
  console.error('! unresolved absolute references:', leftovers)
  throw new Error('standalone build would still need a server')
}

// keep the provenance line, keep the internal pointers out of a public artifact
html = html.replace('<!doctype html>', `<!-- PhosphoPower® Micronized — standalone build generated by scripts/inline.mjs. Do not edit by hand. -->\n<!doctype html>`)

mkdirSync(OUT_DIR, { recursive: true })
const out = join(OUT_DIR, OUT_NAME)
writeFileSync(out, html)
copyFileSync(out, join(ROOT, '..', OUT_NAME)) // /home/user/<name> — easy to open

const kb = (n) => `${(n / 1024).toFixed(0)} KB`
console.log(`✓ ${out}  ${kb(statSync(out).size)}  (css ${kb(css.length)}, js ${kb(js.length)}, image ${kb(b64.length)})`)
console.log(`✓ copied to /home/user/${OUT_NAME}`)
